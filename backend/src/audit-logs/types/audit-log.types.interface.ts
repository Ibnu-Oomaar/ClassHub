/** Who performed the action. System/unauthenticated events (failed logins) have no user. */
export interface AuditActor {
  id: string | null;
  fullName: string;
  role: Role | null;
}

export interface AuditEvent {
  actor: AuditActor | null;
  action: AuditAction;
  entityType: string;
  entityId?: string | null;
  summary: string;
  details?: Record<string, unknown>;
  ipAddress?: string | null;
}

export interface AuditLogView {
  id: string;
  createdAt: Date;
  actorId: string | null;
  actorName: string;
  actorRole: string | null;
  action: string;
  entityType: string;
  entityId: string | null;
  summary: string;
  details: Record<string, unknown> | null;
  ipAddress: string | null;
}
